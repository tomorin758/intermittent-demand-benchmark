#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate LaTeX result tables for the Bench 2026 / TBench evaluation draft.

Reads the three result CSVs in data/ and writes:
  tables/results_<name>.tex -- one full-width table per dataset carrying every metric the paper
                               prints: six core columns plus the tail and demand-class RMSE

Usage: python3 gen_tables.py
"""
import csv, os

# data/ lives OUTSIDE this folder (at ../data) so that uploading the paper folder to
# Overleaf does not drag the ~277 MB evidence bundle along. Resolved from this file's
# own location so the script works from any working directory.
DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")

DATA = {
    "parts":  ("parts.csv",  "Parts (spare parts) demand"),
    "fresh":  ("fresh_retail.csv", "Fresh retail sales"),
    "m5":     ("m5.csv",     "M5 (Walmart retail)"),
}
OUT_DIR = "tables"

# Core columns (main tables): (csv header token, latex header)
CORE_COLS = [
    ("QL(0.5)",   "QL(0.5)"),
    ("Precision", "0P"),
    ("Recall",    "0R"),
    ("F1 score",  "0F1"),
    ("MAE",       "MAE$_{>0}$"),
    ("RMSE",      "RMSE$_{>0}$"),
]
# Printed disaggregated columns: the near-zero segment, the tail, and the four ADI--CV^2 classes.
# The other four segments are not printed: (q10, q25] is empty on all three datasets and
# (q25, q50] on Parts and Fresh retail (integer demand makes those percentiles coincide,
# Section~\ref{sec:reorder}), and the remaining ones enter that section's redundancy analysis.
# All 16 metrics are in the released per-model files.
EXT_COLS = [
    ("[0, q10] RMSE",       "$[0,q_{10}]$"),
    ("(q90, \u221e) RMSE",  "$>q_{90}$"),
    ("intermittent RMSE",   "Int."),
    ("lumpy RMSE",          "Lum."),
    ("smooth RMSE",         "Sm."),
    ("erratic RMSE",        "Err."),
]
ZERO_LIKE = ("Precision", "Recall", "F1 score")

def key_of(ds):
    lower = (ds or "").lower()
    if lower.startswith("m5"):
        return "m5"
    if "fresh" in lower:
        return "fresh"
    if "parts" in lower or "spare" in lower:
        return "parts"
    return None

def read_csv(path):
    with open(path, newline="", encoding="utf-8-sig") as f:
        rows = list(csv.reader(f))
    header = [c.strip() for c in rows[1]]
    start = 2
    while start < len(rows) and len(rows[start]) < 2:
        start += 1
    data = []
    cur_key = None
    all_tokens = [t for t, _ in (CORE_COLS + EXT_COLS)]
    for r in rows[start:]:
        if len(r) < 2 or not r[1].strip():
            continue
        model = r[1].strip()
        if model in ("Model",) or model.lower().startswith("dataset"):
            continue
        if r[0].strip():
            cur_key = key_of(r[0].strip().split("\n")[0])
        row = {}
        for token in all_tokens:
            try:
                idx = header.index(token)
            except ValueError:
                idx = None
            raw = r[idx].strip() if (idx is not None and idx < len(r)) else "-"
            row[token] = raw
        if cur_key:
            data.append((cur_key, model, row))
    return data

def best_of(values, high_better=False):
    nums = [float(v) for v in values if v != "-"]
    if not nums:
        return None
    return max(nums) if high_better else min(nums)

def fmt_cell(v, best, high_better=False):
    if v == "-":
        return "-"
    if best is not None and float(v) == best:
        return "\\textbf{%s}" % v
    return v

def latex_model(model):
    """Compress model names: (tau=0.5) -> dagger marker; tau -> math.

    NOTE: the "(τ=0.5)" tag in the source CSVs selects the TRUNCATED variant
    ('T' if 'τ=0.5' in the row name, else 'NT' — see
    PatchTST_supervised/analysis/audit_tables.py). It is NOT a quantile level.
    The dagger therefore means "truncated at c = 0.5", which is how the
    captions below describe it.
    """
    if model.endswith("(\u03c4=0.5)"):
        return model[: -len("(\u03c4=0.5)")] + "$^{\\dagger}$"
    return model.replace("\u03c4", "$\\tau$")

def emit(name, display, data, cols, fname, floatenv, caption, label=None, width="\\linewidth"):
    rows = [r for r in data if r[0] == name]
    if not rows:
        return
    # Two rows per model: the untruncated row (no dagger) is the ranking reference for the
    # point-forecast columns; the truncated row (dagger) carries the zero-detection metrics.
    # Bold therefore compares like with like.
    def is_trunc(m):
        return m.endswith("(\u03c4=0.5)")
    bests = {}
    for token, _ in cols:
        pool = [r[2][token] for r in rows
                if (is_trunc(r[1]) if token in ZERO_LIKE else not is_trunc(r[1]))]
        bests[token] = best_of(pool, high_better=token in ZERO_LIKE)
    L = []
    L.append("%% %s -- auto-generated by gen_tables.py (do not edit by hand)" % fname)
    L.append("\\begin{%s}[!htbp]" % floatenv)
    L.append("\\centering")
    L.append("\\caption{%s}" % caption)
    L.append("\\label{%s}" % (label or (("tab:ext:%s" if "extended" in fname else "tab:res:%s") % name)))
    L.append("\\renewcommand{\\arraystretch}{0.95}")
    L.append("\\resizebox{%s}{!}{%%" % width)
    L.append("\\begin{tabular}{l%s}" % ("r" * len(cols)))
    L.append("\\toprule")
    # Grouped header so that every abbreviated column says which metric it carries: the six core
    # columns, then RMSE within quantile segments, then RMSE per ADI--CV^2 class.
    n_core, n_seg, n_cls = 6, 2, 4
    assert n_core + n_seg + n_cls == len(cols), (n_core, n_seg, n_cls, len(cols))
    grp = (["\\multicolumn{1}{l}{}"] + ["\\multicolumn{%d}{c}{Core metrics}" % n_core]
           + ["\\multicolumn{%d}{c}{RMSE by segment}" % n_seg]
           + ["\\multicolumn{%d}{c}{RMSE by class}" % n_cls])
    L.append(" & ".join(grp) + " \\\\")
    L.append("\\cmidrule(lr){2-%d}\\cmidrule(lr){%d-%d}\\cmidrule(lr){%d-%d}"
             % (1 + n_core, 2 + n_core, 1 + n_core + n_seg,
                2 + n_core + n_seg, 1 + n_core + n_seg + n_cls))
    L.append("Model & " + " & ".join(h for _, h in cols) + " \\\\")
    L.append("\\midrule")
    for _, model, row in rows:
        cells = [latex_model(model)]
        for token, _ in cols:
            best = bests[token] if (is_trunc(model) == (token in ZERO_LIKE)) else None
            cells.append(fmt_cell(row[token], best, high_better=token in ZERO_LIKE))
        L.append(" & ".join(cells) + " \\\\")
    L.append("\\bottomrule")
    L.append("\\end{tabular}}")
    L.append("\\end{%s}" % floatenv)
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, fname), "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("[wrote] tables/%s (%d models)" % (fname, len(rows)))

def main():
    all_data = []
    for key, (fname, display) in DATA.items():
        # Inside the released artefact bundle the sheet-format CSVs live in tables/<ds>_unified.csv
        # (there is no separate data/ directory); in the paper workspace they live in ../data/.
        cand = [os.path.join(DATA_DIR, fname),
                os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir, 'tables',
                             fname.replace('.csv', '_unified.csv'))]
        path = next((c for c in cand if os.path.exists(c)), cand[0])
        d = read_csv(path)
        all_data += d
        # One full-width table per dataset carrying every metric the paper prints: the six core
        # columns plus the tail and demand-class columns that used to sit in the appendix. A single
        # column cannot hold eleven numeric columns for 45 rows, so the float spans both columns.
        caption = ("Results on the %s dataset: six core metrics, two quantile-segment RMSEs and "
                   "RMSE per ADI--CV$^2$ class. $\\dagger$ marks the same point forecast re-scored "
                   "after truncation at $c=0.5$, the only row carrying zero-detection metrics; bold "
                   "marks the best row of each kind. 0P, 0R and 0F1 are zero-detection precision, "
                   "recall and F1; Int., Lum., Sm. and Err. are the ADI--CV$^2$ classes. Unprinted "
                   "segments are empty by construction or enter Section~\\ref{sec:reorder}; all 16 "
                   "metrics ship in the released files."
                   % display)
        emit(key, display, d, CORE_COLS + EXT_COLS, "results_%s.tex" % key, "table*", caption,
             label="tab:res:%s" % key, width="\\textwidth")
    print("[done] regenerate tables by re-running: python3 gen_tables.py")

if __name__ == "__main__":
    main()
