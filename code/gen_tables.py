#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate LaTeX result tables for the Bench 2026 / TBench evaluation draft.

Reads the three result CSVs in data/ and writes:
  tables/results_<name>.tex          -- core metric table per dataset (single-column friendly,
                                        6 metric columns, spans text width via table*)
  tables/results_extended_<name>.tex -- appendix table: tail + ADI-CV2 regime RMSE per dataset

Usage: python3 gen_tables.py
"""
import csv, os

# data/ lives OUTSIDE this folder (at ../data) so that uploading the paper folder to
# Overleaf does not drag the ~277 MB evidence bundle along. Resolved from this file's
# own location so the script works from any working directory.
DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")

DATA = {
    "parts":  ("parts.csv",  "Parts (spare parts) demand"),
    "fresh":  ("fresh_retail.csv", "Fresh retail sales"),
    "m5":     ("m5.csv",     "M5 (Walmart retail)"),
}
OUT_DIR = "tables"

# Core columns (main tables): (csv header token, latex header)
CORE_COLS = [
    ("QL(0.5)",   "QL(0.5)"),
    ("Precision", "0Precision"),
    ("Recall",    "0Recall"),
    ("F1 score",  "0F1"),
    ("MAE",       "MAE$_{>0}$"),
    ("RMSE",      "RMSE$_{>0}$"),
]
# Extended columns (appendix tables): tail + regime RMSE
EXT_COLS = [
    ("(q90, \u221e) RMSE", "Tail $>q_{90}$"),
    ("intermittent RMSE",  "Interm."),
    ("lumpy RMSE",         "Lumpy"),
    ("smooth RMSE",        "Smooth"),
    ("erratic RMSE",       "Erratic"),
]
ZERO_LIKE = ("Precision", "Recall", "F1 score")

def key_of(ds):
    lower = (ds or "").lower()
    if lower.startswith("m5"):
        return "m5"
    if "fresh" in lower:
        return "fresh"
    if "parts" in lower or "spare" in lower:
        return "parts"
    return None

def read_csv(path):
    with open(path, newline="", encoding="utf-8-sig") as f:
        rows = list(csv.reader(f))
    header = [c.strip() for c in rows[1]]
    start = 2
    while start < len(rows) and len(rows[start]) < 2:
        start += 1
    data = []
    cur_key = None
    all_tokens = [t for t, _ in (CORE_COLS + EXT_COLS)]
    for r in rows[start:]:
        if len(r) < 2 or not r[1].strip():
            continue
        model = r[1].strip()
        if model in ("Model",) or model.lower().startswith("dataset"):
            continue
        if r[0].strip():
            cur_key = key_of(r[0].strip().split("\n")[0])
        row = {}
        for token in all_tokens:
            try:
                idx = header.index(token)
            except ValueError:
                idx = None
            raw = r[idx].strip() if (idx is not None and idx < len(r)) else "-"
            row[token] = raw
        if cur_key:
            data.append((cur_key, model, row))
    return data

def best_of(values, high_better=False):
    nums = [float(v) for v in values if v != "-"]
    if not nums:
        return None
    return max(nums) if high_better else min(nums)

def fmt_cell(v, best, high_better=False):
    if v == "-":
        return "-"
    if best is not None and float(v) == best:
        return "\\textbf{%s}" % v
    return v

def latex_model(model):
    """Compress model names: (tau=0.5) -> dagger marker; tau -> math.

    NOTE: the "(τ=0.5)" tag in the source CSVs selects the TRUNCATED variant
    ('T' if 'τ=0.5' in the row name, else 'NT' — see
    PatchTST_supervised/analysis/audit_tables.py). It is NOT a quantile level.
    The dagger therefore means "truncated at c = 0.5", which is how the
    captions below describe it.
    """
    if model.endswith("(\u03c4=0.5)"):
        return model[: -len("(\u03c4=0.5)")] + "$^{\\dagger}$"
    return model.replace("\u03c4", "$\\tau$")

def emit(name, display, data, cols, fname, floatenv, caption):
    rows = [r for r in data if r[0] == name]
    if not rows:
        return
    # Two rows per model: the untruncated row (no dagger) is the ranking reference for the
    # point-forecast columns; the truncated row (dagger) carries the zero-detection metrics.
    # Bold therefore compares like with like.
    def is_trunc(m):
        return m.endswith("(\u03c4=0.5)")
    bests = {}
    for token, _ in cols:
        pool = [r[2][token] for r in rows
                if (is_trunc(r[1]) if token in ZERO_LIKE else not is_trunc(r[1]))]
        bests[token] = best_of(pool, high_better=token in ZERO_LIKE)
    L = []
    L.append("%% %s -- auto-generated by gen_tables.py (do not edit by hand)" % fname)
    L.append("\\begin{%s}[!htbp]" % floatenv)
    L.append("\\centering")
    L.append("\\caption{%s}" % caption)
    L.append("\\label{%s}" % (("tab:ext:%s" if "extended" in fname else "tab:res:%s") % name))
    L.append("\\resizebox{\\linewidth}{!}{%%")
    L.append("\\begin{tabular}{l%s}" % ("r" * len(cols)))
    L.append("\\toprule")
    L.append("Model & " + " & ".join(h for _, h in cols) + " \\\\")
    L.append("\\midrule")
    for _, model, row in rows:
        cells = [latex_model(model)]
        for token, _ in cols:
            best = bests[token] if (is_trunc(model) == (token in ZERO_LIKE)) else None
            cells.append(fmt_cell(row[token], best, high_better=token in ZERO_LIKE))
        L.append(" & ".join(cells) + " \\\\")
    L.append("\\bottomrule")
    L.append("\\end{tabular}}")
    L.append("\\end{%s}" % floatenv)
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, fname), "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("[wrote] tables/%s (%d models)" % (fname, len(rows)))

def main():
    all_data = []
    for key, (fname, display) in DATA.items():
        d = read_csv(os.path.join(DATA_DIR, fname))
        all_data += d
        # core table: fits easily inside text width (single- or double-column)
        caption = ("Results on the %s dataset: every model appears twice, once scored on its own "
                   "point forecast (upper row) and once with the same forecast re-scored after "
                   "truncating both sides at $c=0.5$ ($\\dagger$). QL(0.5) is the pinball loss at the "
                   "median over all test points; MAE$_{>0}$ and RMSE$_{>0}$ use only points with a "
                   "non-zero actual, so they are not twice QL(0.5). Zero-detection metrics "
                   "(0Precision/0Recall/0F1) exist only in the truncated row: there both forecast and "
                   "actual are classified as ``no demand'' when they fall below $c$. The untruncated "
                   "rows are the ranking reference. Bold marks the best value among untruncated rows "
                   "for the point-forecast columns and among truncated rows for the zero-detection "
                   "columns. Tail and demand-regime errors are in Table~\\ref{tab:ext:%s}."
                   % (display, key))
        emit(key, display, d, CORE_COLS, "results_%s.tex" % key, "table", caption)
        # extended appendix table
        caption2 = ("Extended metrics on the %s dataset for the same rows as the core table: tail "
                    "RMSE on the largest non-zero demands (actuals above their $q_{90}$) and RMSE per "
                    "ADI--CV$^2$ demand class (Interm. = intermittent). $\\dagger$: the truncated row "
                    "(forecast and actuals below $c=0.5$ set to zero). Bold marks the best value among "
                    "untruncated rows." % display)
        emit(key, display, d, EXT_COLS, "results_extended_%s.tex" % key, "table", caption2)
    print("[done] regenerate tables by re-running: python3 gen_tables.py")

if __name__ == "__main__":
    main()
